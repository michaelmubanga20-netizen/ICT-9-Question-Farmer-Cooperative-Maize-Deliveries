

CREATE TABLE farmers(farmer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,farmer_number varchar(30) NOT NULL UNIQUE,full_name text NOT NULL);
CREATE TABLE deliveries(
 delivery_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,farmer_id integer NOT NULL REFERENCES farmers(farmer_id),
 grade char(1) NOT NULL CHECK(grade IN('A','B','C')),
 weight_kg numeric(12,2) NOT NULL CHECK(weight_kg>0),
 unit_rate numeric(8,2) NOT NULL,total_value numeric(14,2) NOT NULL,
 delivered_on date NOT NULL,is_paid boolean NOT NULL DEFAULT false
);
CREATE TABLE daily_purchases(purchase_date date PRIMARY KEY,total_weight numeric(14,2) NOT NULL,total_value numeric(14,2) NOT NULL);
