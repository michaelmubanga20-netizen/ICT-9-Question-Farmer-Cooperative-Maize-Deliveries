CREATE OR REPLACE FUNCTION fn_maize_rate(p_grade char(1))
RETURNS numeric(8,2) LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
 IF p_grade IS NULL THEN RAISE EXCEPTION 'Grade is required'; END IF;
 CASE upper(p_grade)
  WHEN 'A' THEN RETURN 5.00;
  WHEN 'B' THEN RETURN 4.00;
  WHEN 'C' THEN RETURN 3.00;
  ELSE RAISE EXCEPTION 'Unsupported maize grade %',p_grade;
 END CASE;
END $$;

CREATE OR REPLACE FUNCTION trg_delivery_price_fn()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.weight_kg IS NULL OR NEW.weight_kg<=0 THEN RAISE EXCEPTION 'Weight must be positive'; END IF;
 NEW.grade:=upper(NEW.grade);
 NEW.unit_rate:=fn_maize_rate(NEW.grade);
 NEW.total_value:=round(NEW.weight_kg*NEW.unit_rate,2);
 RETURN NEW;
END $$;
CREATE TRIGGER deliveries_set_price BEFORE INSERT OR UPDATE ON deliveries
FOR EACH ROW EXECUTE FUNCTION trg_delivery_price_fn();

CREATE OR REPLACE PROCEDURE pr_receive_delivery(p_farmer_id integer,p_grade char(1),p_weight numeric,p_date date)
LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM farmers WHERE farmer_id=p_farmer_id) THEN RAISE EXCEPTION 'Unknown farmer'; END IF;
 IF p_grade IS NULL OR upper(p_grade) NOT IN('A','B','C') OR p_weight IS NULL OR p_weight<=0 OR p_date IS NULL THEN
  RAISE EXCEPTION 'Invalid delivery inputs';
 END IF;
 INSERT INTO deliveries(farmer_id,grade,weight_kg,unit_rate,total_value,delivered_on,is_paid)
 VALUES(p_farmer_id,upper(p_grade),p_weight,0,0,p_date,false);
END $$;

